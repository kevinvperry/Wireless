#!/usr/bin/env python3
"""Generate a conservative ACMA import from exact BSL matches.

Based on Australian Communications and Media Authority information.
Only a station's existing licence_numbers_json value that exactly matches an
ACMA BSL is accepted. Names and frequencies are never used as sole identity.
"""
import csv, json, hashlib, re
from pathlib import Path
from datetime import datetime
ROOT=Path(__file__).resolve().parents[2]
STATIONS=ROOT/'research/acma-directory-upgrade/remote-stations.json'
ACMA=ROOT/'research/db-audit/acma/transmitter-excel'
COMMUNITY=ROOT/'research/community-network-audit/acma-community-licences-enriched.json'
OUT=ROOT/'station-directory/migrations/0037_import_exact_acma_records.sql'
SUMMARY=ROOT/'research/acma-directory-upgrade/import-summary.json'
SOURCE='https://www.acma.gov.au/list-transmitters-licence-broadcast'
VERIFIED='2026-07-13'

def q(v): return "'"+str(v or '').replace("'","''")+"'"
def dms(value):
    m=re.fullmatch(r'\s*(\d+)\s+(\d+)\s+([0-9.]+)([NSEW])\s*',value or '')
    if not m:return None
    d,mn,s,hem=m.groups(); n=float(d)+float(mn)/60+float(s)/3600
    return -n if hem in 'SW' else n
def iso(value):
    try:return datetime.strptime(value,'%d/%m/%Y').strftime('%Y-%m-%d')
    except:return ''

data=json.load(open(STATIONS))[0]['results']
stations={s['id']:s for s in data}
by_number={}
for s in data:
    for n in json.loads(s['licence_numbers_json'] or '[]'):
        by_number.setdefault(str(n).strip(),[]).append(s)
rows=[]
for filename,band,unit,power_col,power_type in [('AM.csv','AM','kHz','Transmitter Power (W)','Transmitter power'),('FM.csv','FM','MHz','Maximum ERP (W)','Maximum ERP')]:
    with open(ACMA/filename,newline='',encoding='utf-8-sig') as f:
        for row in csv.DictReader(f):
            bsl=str(row.get('BSL') or '').strip()
            if bsl and bsl in by_number and len(by_number[bsl])==1:
                row.update(_band=band,_unit=unit,_power_col=power_col,_power_type=power_type,_station=by_number[bsl][0],_bsl=bsl)
                rows.append(row)
community={str(r['licence']):r for r in json.load(open(COMMUNITY))}
# Remove exact duplicate ACMA rows (the source workbook contains some repeats).
unique={}
for r in rows:
    key=(r['_station']['id'],r.get('Licence Number',''),r.get('Technical Specification Number',''),r.get('Site id') or r.get('Site Id',''),r.get('Frequency(kHz)') or r.get('Frequency(MHz)',''))
    unique[key]=r
rows=list(unique.values())
by_station={}
for r in rows:by_station.setdefault(r['_station']['id'],[]).append(r)
lines=['-- Generated by scripts/import-acma-records.py using exact existing BSL matches only.', '-- Based on Australian Communications and Media Authority information.', '']
for sid,group in sorted(by_station.items()):
    first=group[0]; bsl=first['_bsl']; comm=community.get(bsl,{})
    callsigns=sorted({r.get('Callsign','').strip() for r in group if r.get('Callsign','').strip()})
    areas=sorted({r.get('Licence Area','').strip() for r in group if r.get('Licence Area','').strip()})
    area_ids=sorted({r.get('Licence Area ID','').strip() for r in group if r.get('Licence Area ID','').strip()})
    purposes=sorted({r.get('Purpose','').strip() for r in group if r.get('Purpose','').strip()})
    primary_location=(json.loads(first['_station']['cities_json'] or '[]') or [first.get('Area Served','')])[0]
    values={
      'callsign':callsigns[0] if len(callsigns)==1 else ', '.join(callsigns),
      'licence_category':purposes[0] if len(purposes)==1 else ', '.join(purposes),
      'acma_service_licence_number':bsl,
      'licence_area_name':comm.get('area') or (areas[0] if len(areas)==1 else ', '.join(areas)),
      'licence_area_id':area_ids[0] if len(area_ids)==1 else ', '.join(area_ids),
      'primary_location':primary_location,
      'metro_regional':comm.get('region',''),
      'community_interest':comm.get('interest',''),
      'licence_commenced_at':iso(comm.get('commenced','')),
      'licence_expires_at':iso(comm.get('expiry','')),
      'acma_verified_at':VERIFIED,
      'acma_source_url':SOURCE,
    }
    setters=','.join(f'{k}={q(v)}' for k,v in values.items())
    lines.append(f'UPDATE stations SET {setters},version=version+1,updated_at=strftime(\'%Y-%m-%dT%H:%M:%fZ\',\'now\'),updated_by=\'acma-exact-bsl-import\' WHERE id={q(sid)};')
    max_power=max((float(r.get(r['_power_col']) or 0) for r in group),default=0)
    for r in group:
        freq=r.get('Frequency(kHz)') or r.get('Frequency(MHz)') or ''
        site_id=r.get('Site id') or r.get('Site Id') or ''
        raw='|'.join([sid,r.get('Licence Number',''),r.get('Technical Specification Number',''),site_id,freq,r['_unit']])
        txid='acma_'+hashlib.sha256(raw.encode()).hexdigest()[:24]
        power=float(r.get(r['_power_col']) or 0) if r.get(r['_power_col']) else None
        vals=[txid,sid,r.get('Licence Number',''),r.get('Technical Specification Number',''),site_id,r.get('Site Name',''),r.get('Area Served',''),float(freq) if freq else None,r['_unit'],r['_band'],r.get('Purpose',''),r.get('Status',''),dms(r.get('Latitude','')),dms(r.get('Longitude','')),power,r['_power_type'],r.get('Antenna Pattern',''),r.get('Polarisation',''),r.get('Licence Area',''),r.get('Licence Area ID',''),'',1 if power==max_power and max_power>0 else 0,SOURCE,VERIFIED]
        rendered=','.join('NULL' if v is None else str(v) if isinstance(v,(int,float)) else q(v) for v in vals)
        # Production station IDs are deliberately absent from fresh test databases.
        # Keep this data migration replayable by inserting only when its station exists.
        lines.append('INSERT OR REPLACE INTO station_transmitters(id,station_id,transmitter_licence_number,technical_specification_number,site_id,site_name,area_served,frequency_value,frequency_unit,band,purpose,status,latitude,longitude,power_watts,power_type,antenna_pattern,polarisation,licence_area_name,licence_area_id,transmitter_licensee,is_primary,source_url,verified_at) SELECT '+rendered+' WHERE EXISTS(SELECT 1 FROM stations WHERE id='+q(sid)+');')
lines += ['',"INSERT INTO audit_log(id,actor_id,actor_email,action,station_id,details_json,created_at) VALUES('acma-exact-import-0037-2026-10-14','system','system@wireless.local','catalogue.acma-records-imported',NULL,"+q(json.dumps({'method':'exact existing BSL match','stations':len(by_station),'transmitters':len(rows),'source':SOURCE,'attribution':'Based on Australian Communications and Media Authority information'},separators=(',',':')))+",strftime('%Y-%m-%dT%H:%M:%fZ','now'));", "UPDATE catalogue_meta SET revision=revision+1,updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE id=1;"]
OUT.write_text('\n'.join(lines)+'\n')
summary={'stations_matched':len(by_station),'transmitters_imported':len(rows),'community_licences_enriched':sum(1 for sid,g in by_station.items() if g[0]['_bsl'] in community),'unmatched_stations_with_legacy_licence':sum(1 for n,v in by_number.items() if not any(r['_bsl']==n for r in rows)),'source':SOURCE,'verified_at':VERIFIED}
SUMMARY.write_text(json.dumps(summary,indent=2)+'\n')
print(json.dumps(summary,indent=2))
